"""The Arabic joining-forms table in RiptOPL's src/ripps2tr.c (RIPPS2 build 104), made from Unicode's own data.

Each Arabic letter that has presentation forms (U+FB50..U+FDFF, U+FE70..U+FEFF) gets its isolated, final, initial
and medial forms; a letter with no initial or medial form joins to the letter before it only (alef, dal, reh, waw,
...). Lam with alef is a ligature of its own, kept apart in ripps2tr.c. Run it and paste the output between the
GENERATED markers:

    python3 elf/lang/make_arabic_forms.py
"""
import unicodedata

FORMS = ('isolated', 'final', 'initial', 'medial')


def table():
    found = {}
    # forms B first: the standard letters' main forms; forms A then adds the Persian and Urdu letters
    for c in list(range(0xFE70, 0xFF00)) + list(range(0xFB50, 0xFE00)):
        d = unicodedata.decomposition(chr(c)).split()
        if len(d) != 2 or d[0].strip('<>') not in FORMS:
            continue
        base = int(d[1], 16)
        if not 0x0620 <= base <= 0x06FF:
            continue
        slot = found.setdefault(base, [0, 0, 0, 0])
        k = FORMS.index(d[0].strip('<>'))
        if slot[k] == 0:
            slot[k] = c
    return found


def main():
    rows = table()
    print('// GENERATED by ps2-pillars elf/lang/make_arabic_forms.py (Unicode %s): base, isolated, final, initial, '
          'medial' % unicodedata.unidata_version)
    print('static const u16 trArab[][5] = {')
    for base in sorted(rows):
        iso, fin, ini, med = rows[base]
        print('    {0x%04X, 0x%04X, 0x%04X, 0x%04X, 0x%04X}, // %s' % (base, iso, fin, ini, med, unicodedata.name(chr(base))))
    print('};')
    print('// GENERATED END')


if __name__ == '__main__':
    main()
